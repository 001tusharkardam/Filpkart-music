// Parses raw LRC text into [{ time: seconds, text: string }]
export function parseLrcLyrics(lrcText) {
  if (!lrcText || typeof lrcText !== 'string') return [];
  const lines = lrcText.split('\n');
  const result = [];
  const timeRegex = /\[(\d{1,2}):(\d{1,2}(?:\.\d+)?)\](.*)/;

  for (const line of lines) {
    const match = line.match(timeRegex);
    if (match) {
      const minutes = parseInt(match[1], 10);
      const seconds = parseFloat(match[2]);
      const text = match[3].trim();
      if (text) {
        result.push({
          time: Math.round((minutes * 60 + seconds) * 10) / 10,
          text: text
        });
      }
    }
  }

  const sorted = result.sort((a, b) => a.time - b.time);
  if (sorted.length > 0 && sorted[0].time > 2.5) {
    sorted.unshift({ time: 0, text: '♪ (Music Intro) ♪' });
  }
  return sorted;
}

// Cleans track and artist names for high-accuracy search
export function cleanSearchName(str) {
  if (!str) return '';
  return str
    .replace(/\(from[^)]+\)/gi, '')
    .replace(/\(feat[^)]+\)/gi, '')
    .replace(/\(official[^)]+\)/gi, '')
    .replace(/feat\..*/gi, '')
    .replace(/ft\..*/gi, '')
    .replace(/official.*audio/gi, '')
    .replace(/official.*video/gi, '')
    .replace(/\[[^\]]+\]/g, '')
    .replace(/[^\w\s]/gi, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

function normalizeKey(str) {
  if (!str) return '';
  return str.toLowerCase().replace(/[^a-z0-9]/g, '');
}

// Match against built-in accurate lyrics database
export function getBuiltinLyrics(trackTitle) {
  if (!trackTitle) return null;
  const clean = normalizeKey(cleanSearchName(trackTitle));

  for (const [key, lines] of Object.entries(BUILTIN_ACCURATE_LYRICS)) {
    const normKey = normalizeKey(key);
    if (clean.includes(normKey) || normKey.includes(clean)) {
      return lines;
    }
  }

  return null;
}

// Fetch synchronized lyrics:
// 1) Instant match in Built-in 100% Studio LRC DB
// 2) Live search query on LRCLIB (open-source synchronized lyrics API)
// 3) Exact track/artist query on LRCLIB
// 4) Clean fallback
export async function fetchSynchronizedLyrics(trackTitle, artistName, durationSec = 210) {
  // 1. Check instant accurate built-in studio database
  const builtin = getBuiltinLyrics(trackTitle);
  if (builtin && builtin.length > 0) {
    return builtin;
  }

  const cleanTitle = cleanSearchName(trackTitle);
  const cleanArtist = cleanSearchName(artistName).split(' ')[0] || '';

  // 2. Fetch live from LRCLIB API Search
  try {
    const searchQuery = encodeURIComponent(`${cleanTitle} ${cleanArtist}`.trim());
    const controller = new AbortController();
    const timeout = setTimeout(() => controller.abort(), 4500);

    const searchRes = await fetch(`https://lrclib.net/api/search?q=${searchQuery}`, {
      signal: controller.signal,
      headers: { 'User-Agent': 'FlipkartMusic/2.0' }
    });
    clearTimeout(timeout);

    if (searchRes.ok) {
      const data = await searchRes.json();
      if (Array.isArray(data) && data.length > 0) {
        const bestSynced = data.find(item => item.syncedLyrics && item.syncedLyrics.length > 40);
        if (bestSynced) {
          const parsed = parseLrcLyrics(bestSynced.syncedLyrics);
          if (parsed.length > 0) return parsed;
        }

        const bestPlain = data.find(item => item.plainLyrics && item.plainLyrics.length > 40);
        if (bestPlain) {
          const plainLines = bestPlain.plainLyrics.split('\n').map(l => l.trim()).filter(Boolean);
          if (plainLines.length > 0) {
            const step = Math.max(3, Math.floor((durationSec || 200) / plainLines.length));
            return plainLines.map((text, idx) => ({
              time: idx * step,
              text
            }));
          }
        }
      }
    }
  } catch (err) {
    // API timeout or network offline
  }

  // 3. Fallback to LRCLIB Exact Get Endpoint
  try {
    const getUrl = `https://lrclib.net/api/get?track_name=${encodeURIComponent(cleanTitle)}&artist_name=${encodeURIComponent(cleanArtist)}`;
    const controller = new AbortController();
    const timeout = setTimeout(() => controller.abort(), 3500);

    const res = await fetch(getUrl, {
      signal: controller.signal,
      headers: { 'User-Agent': 'FlipkartMusic/2.0' }
    });
    clearTimeout(timeout);

    if (res.ok) {
      const item = await res.json();
      if (item.syncedLyrics) {
        const parsed = parseLrcLyrics(item.syncedLyrics);
        if (parsed.length > 0) return parsed;
      }
    }
  } catch (err) {
    // Fallback
  }

  // 4. Clean dignified presentation for instrumental or unregistered songs
  return [
    { time: 0, text: `♪ ${trackTitle} ♪` },
    { time: 4, text: `Vocals & Performance by ${artistName || 'Artist'}` },
    { time: 10, text: '♪ (Enjoy the melody in 320kbps Ultra HD) ♪' },
    { time: Math.floor((durationSec || 200) * 0.4), text: '♪ (Instrumental Beats & Rhythm) ♪' },
    { time: Math.floor((durationSec || 200) * 0.8), text: `♪ ${trackTitle} - Flipkart Music VIP ♪` }
  ];
}
